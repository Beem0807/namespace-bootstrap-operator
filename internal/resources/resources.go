// Package resources translates a NamespaceProfile into the Kubernetes objects
// that enforce it.
//
// Everything here is a pure function: no client, no context, no I/O. Given a
// profile, each builder returns what the cluster *should* contain, and makes no
// attempt to discover or change what it currently does. That separation is
// deliberate — this is where almost all of the operator's real logic lives, so
// keeping it free of cluster access means it can be tested exhaustively in
// milliseconds, and the controller is left holding only orchestration.
//
// Builders return server-side apply configurations rather than ordinary typed
// objects. An apply configuration carries *only* the fields the operator
// intends to own, so applying one tells the API server exactly that much and
// nothing more: unrelated labels, annotations and fields set by other actors
// are left alone, and a field the operator stops declaring is released rather
// than lingering. Building typed structs instead would send every zero value
// as an assertion of ownership.
package resources

import (
	"strconv"

	metav1 "k8s.io/apimachinery/pkg/apis/meta/v1"

	platformv1alpha1 "github.com/Beem0807/namespace-bootstrap-operator/api/v1alpha1"
)

// OwnershipLabels are the labels stamped on every object the operator
// generates, including the target namespace.
//
// The pair is what makes ownership decidable later: ManagedByLabel says this
// operator produced the object, and ProfileLabel says which profile it was
// produced for. Both must be present and the profile must match before the
// operator will write to or delete anything, which is what prevents it from
// touching an identically named object belonging to someone else.
func OwnershipLabels(profile *platformv1alpha1.NamespaceProfile) map[string]string {
	return map[string]string{
		platformv1alpha1.ManagedByLabel: platformv1alpha1.OperatorName,
		platformv1alpha1.ProfileLabel:   profile.Name,
	}
}

// IsOwnedBy reports whether an existing object carries this profile's
// ownership labels.
//
// A false result is not an error: it means the object is foreign, and the
// operator must leave it untouched and report a conflict rather than assume it
// may take over. Adoption is the explicit, opt-in path for claiming such an
// object, and it goes through this same check once the labels have been
// written.
func IsOwnedBy(obj metav1.Object, profile *platformv1alpha1.NamespaceProfile) bool {
	labels := obj.GetLabels()
	return labels[platformv1alpha1.ManagedByLabel] == platformv1alpha1.OperatorName &&
		labels[platformv1alpha1.ProfileLabel] == profile.Name
}

// IsManagedByOperator reports whether an object was generated by this operator
// for *some* profile.
//
// This is the weaker question, and it is the right one when deciding whether an
// event is interesting at all: a quota labelled for a different profile still
// concerns this operator, whereas one labelled by nobody does not.
func IsManagedByOperator(obj metav1.Object) bool {
	return obj.GetLabels()[platformv1alpha1.ManagedByLabel] == platformv1alpha1.OperatorName
}

// ManagingProfile returns the name of the profile an object is labelled for,
// or the empty string if it carries no such label.
func ManagingProfile(obj metav1.Object) string {
	return obj.GetLabels()[platformv1alpha1.ProfileLabel]
}

// appliedGenerationAnnotation records which generation of the profile produced
// an object.
//
// The operator does not rely on it to converge — server-side apply handles
// that — but it answers "which version of the profile produced this object?"
// directly in `kubectl describe`, which is the first thing anyone wants to know
// when a namespace does not look the way they expect.
func appliedGenerationAnnotation(profile *platformv1alpha1.NamespaceProfile) map[string]string {
	return map[string]string{
		platformv1alpha1.AppliedGenerationAnnotation: strconv.FormatInt(profile.Generation, 10),
	}
}

// ManageDecision is whether the operator may write to an existing object.
type ManageDecision int

const (
	// ManageOwned means the object already carries this profile's ownership
	// labels.
	ManageOwned ManageDecision = iota

	// ManageAdopt means the object is not the operator's but the profile has
	// opted into adoption, so it may be taken over.
	ManageAdopt

	// ManageRefuseForeign means the object belongs to something outside this
	// operator and adoption was not requested.
	ManageRefuseForeign

	// ManageRefuseOtherProfile means the object was generated by this operator
	// for a different profile. This is never adoptable: two profiles competing
	// over one namespace is a conflict to be resolved by ownership rules, not
	// by letting whichever reconciles last seize the object.
	ManageRefuseOtherProfile
)

// CanManage classifies an existing object's ownership relative to a profile.
//
// It classifies; it does not decide. Whether a given classification permits a
// write depends on context the caller holds — specifically, whether namespace
// ownership has already been arbitrated — so that judgement belongs in the
// controller rather than here.
//
// The order of the checks still matters. An object generated by this operator
// for another profile is reported as such before adoption is considered, so
// spec.adoptExisting can never be mistaken for a way to seize a namespace from
// a peer profile.
func CanManage(obj metav1.Object, profile *platformv1alpha1.NamespaceProfile) ManageDecision {
	if IsOwnedBy(obj, profile) {
		return ManageOwned
	}
	if IsManagedByOperator(obj) {
		return ManageRefuseOtherProfile
	}
	if profile.Spec.AdoptionAllowed() {
		return ManageAdopt
	}
	return ManageRefuseForeign
}
