package v1alpha1

// This file holds the operator's public contract with the cluster: the labels
// and annotations it writes, the names it generates, and the vocabulary of its
// status conditions. These are things users read, grep for and write policy
// against, so they live beside the API types rather than inside the controller.

// OperatorName identifies this operator in labels and as the server-side apply
// field manager. Managed-field ownership is keyed on this string, so changing
// it would orphan every field the operator currently owns.
const OperatorName = "namespace-bootstrap-operator"

// Ownership labels. Every object the operator generates carries both. The pair
// is what makes ownership decidable: ManagedByLabel says "this operator owns
// it" and ProfileLabel says "on behalf of this profile". An object missing
// either is treated as foreign and is never written to without explicit
// adoption.
const (
	// ManagedByLabel marks an object as generated by this operator. It uses
	// the standard Kubernetes label so the usual tooling recognises it.
	ManagedByLabel = "app.kubernetes.io/managed-by"

	// ProfileLabel names the NamespaceProfile an object was generated for.
	// NamespaceProfile is cluster-scoped, so the profile name alone is
	// unambiguous.
	ProfileLabel = "platform.nabeem.com/profile"
)

// Annotations the operator reads or writes.
const (
	// AdoptedAnnotation is set to "true" on a namespace the operator adopted
	// rather than created.
	//
	// It is the record that makes adoption safe: the operator refuses to
	// delete any namespace carrying it, regardless of lifecycle settings,
	// because something else created that namespace and the operator cannot
	// know what else depends on it.
	AdoptedAnnotation = "platform.nabeem.com/adopted"

	// ConfirmNamespaceDeletionAnnotation must be set on a NamespaceProfile,
	// with a value equal to spec.namespace, before the operator will delete
	// the namespace on profile removal.
	//
	// This is the "type the name to confirm" pattern. A single boolean field
	// is too easy to copy between profiles or set by a templating mistake;
	// requiring the namespace name to be repeated means the confirmation
	// cannot be correct for the wrong namespace.
	ConfirmNamespaceDeletionAnnotation = "platform.nabeem.com/confirm-namespace-deletion"

	// AppliedGenerationAnnotation records the profile metadata.generation that
	// a managed resource was rendered from.
	//
	// The operator does not need it to converge — server-side apply handles
	// that — but it answers "which version of the profile produced this
	// object?" directly in `kubectl describe`, which is the first question
	// anyone asks when a namespace does not look the way they expect.
	AppliedGenerationAnnotation = "platform.nabeem.com/applied-generation"

	// ManagedQuotaKeysAnnotation records, on the generated ResourceQuota, the
	// sorted list of hard-limit keys the operator last applied.
	//
	// A ResourceQuota's spec.hard is a map, so server-side apply tracks
	// ownership key by key — and because spec.quota.objectCounts lets a user
	// name any key they like, the set the operator owns cannot be derived from
	// the profile alone. Without this record, withdrawing an entry from
	// objectCounts would be indistinguishable from a limit the operator never
	// set, and the stale limit would linger forever.
	//
	// Storing it as an annotation rather than reading the object's managedFields
	// keeps the operator's claim legible: `kubectl describe resourcequota`
	// states plainly which limits are the profile's and which belong to
	// whoever else wrote them.
	ManagedQuotaKeysAnnotation = "platform.nabeem.com/managed-quota-keys"
)

// CleanupFinalizer blocks deletion of a NamespaceProfile until the operator
// has run its cleanup.
//
// A finalizer is required here because cleanup is a decision, not a static
// object graph: whether to delete the namespace depends on the lifecycle
// settings, the confirmation annotation and whether the namespace was adopted,
// and whether to remove the generated policy objects depends on a flag that
// can be flipped after those objects were created. Owner references are fixed
// at creation time and cannot express any of that, and relying on them for the
// namespace would make deleting a profile capable of deleting live workloads.
const CleanupFinalizer = "platform.nabeem.com/cleanup"

// Deterministic names for the resources the operator generates. One set per
// namespace, since a namespace is governed by exactly one profile.
//
// The names are fixed rather than derived from the profile name so that
// renaming a profile cannot strand a previously generated policy under an old
// name. They are also predictable enough to reference from documentation and
// from `kubectl get` without first reading the profile.
const (
	// ResourceQuotaName is the generated ResourceQuota.
	ResourceQuotaName = "nsprofile-quota"

	// LimitRangeName is the generated LimitRange.
	LimitRangeName = "nsprofile-limits"

	// DenyIngressPolicyName denies all ingress by default.
	DenyIngressPolicyName = "nsprofile-default-deny-ingress"

	// DenyEgressPolicyName denies all egress by default.
	DenyEgressPolicyName = "nsprofile-default-deny-egress"

	// AllowDNSPolicyName permits egress to cluster DNS.
	AllowDNSPolicyName = "nsprofile-allow-dns"

	// AllowSameNamespacePolicyName permits traffic within the namespace.
	AllowSameNamespacePolicyName = "nsprofile-allow-same-namespace"

	// AllowKubeAPIPolicyName permits egress to the Kubernetes API server.
	AllowKubeAPIPolicyName = "nsprofile-allow-kube-api"

	// AllowEgressToNamespacesPolicyName permits egress to named namespaces.
	AllowEgressToNamespacesPolicyName = "nsprofile-allow-egress-to-namespaces"

	// AllowIngressFromNamespacesPolicyName permits ingress from named
	// namespaces.
	AllowIngressFromNamespacesPolicyName = "nsprofile-allow-ingress-from-namespaces"
)

// Pod Security Admission label keys, as defined by Kubernetes. The operator
// writes these onto the namespace; the API server's built-in admission plugin
// reads them. See
// https://kubernetes.io/docs/concepts/security/pod-security-admission/
const (
	PSAEnforceLabel        = "pod-security.kubernetes.io/enforce"
	PSAEnforceVersionLabel = "pod-security.kubernetes.io/enforce-version"
	PSAAuditLabel          = "pod-security.kubernetes.io/audit"
	PSAAuditVersionLabel   = "pod-security.kubernetes.io/audit-version"
	PSAWarnLabel           = "pod-security.kubernetes.io/warn"
	PSAWarnVersionLabel    = "pod-security.kubernetes.io/warn-version"
)

// Status condition types. Ready is the one to alert on; the others explain it.
const (
	// ConditionReady is True when every resource the profile requests exists
	// and matches it.
	ConditionReady = "Ready"

	// ConditionProgressing is True while the operator is actively converging
	// toward the desired state.
	ConditionProgressing = "Progressing"

	// ConditionDegraded is True when the operator could not reach the desired
	// state. It is distinct from Ready=False: a profile blocked by a namespace
	// conflict is not Ready but is working exactly as designed, whereas
	// Degraded means something went wrong.
	ConditionDegraded = "Degraded"

	// ConditionPolicyCompliant is True when the live resources match the
	// profile — that is, no drift the operator has not already corrected. It
	// separates "the policy is in force" from "the operator is healthy", which
	// are different questions for an auditor and for an on-call engineer.
	ConditionPolicyCompliant = "PolicyCompliant"
)

// Event actions. The events.k8s.io/v1 API separates *why* something happened
// (the reason) from *what the operator did about it* (the action), and both are
// required. Keeping the set small keeps events aggregatable: the API server
// collapses repeated events sharing a reason and action into one object with a
// count, which is what stops a profile blocked on a conflict from flooding the
// cluster's event stream.
const (
	// ActionProvisioning is creating a resource the profile declares.
	ActionProvisioning = "Provisioning"

	// ActionCorrecting is rewriting a managed resource that had diverged.
	ActionCorrecting = "Correcting"

	// ActionReconciling is evaluating the profile, used for events that report
	// a change in overall state rather than an individual write.
	ActionReconciling = "Reconciling"
)

// Condition reasons. Kubernetes requires reasons to be CamelCase single
// tokens; these are the complete set the operator emits.
const (
	// ReasonProvisioned means all requested resources were created and match.
	ReasonProvisioned = "Provisioned"

	// ReasonProvisioning means resources are still being created or updated.
	ReasonProvisioning = "Provisioning"

	// ReasonNamespaceConflict means another NamespaceProfile already owns the
	// target namespace. The operator stays idle rather than fighting it.
	ReasonNamespaceConflict = "NamespaceConflict"

	// ReasonNamespaceNotAdopted means the target namespace already exists
	// without this operator's ownership labels and spec.adoptExisting is
	// false.
	ReasonNamespaceNotAdopted = "NamespaceNotAdopted"

	// ReasonForeignResource means an object occupies one of the operator's
	// deterministic names without its ownership labels.
	ReasonForeignResource = "ForeignResource"

	// ReasonNamespaceTerminating means the target namespace is being deleted.
	// The operator waits rather than attempting to write into it, because
	// writes to a terminating namespace are rejected.
	ReasonNamespaceTerminating = "NamespaceTerminating"

	// ReasonDriftCorrected means the operator rewrote a managed resource that
	// had been changed outside the profile.
	ReasonDriftCorrected = "DriftCorrected"

	// ReasonReconcileError means a Kubernetes API call failed. These are
	// usually transient and retried with backoff.
	ReasonReconcileError = "ReconcileError"

	// ReasonCleanupBlocked means cleanup could not complete, so the profile
	// remains in deletion with its finalizer held.
	ReasonCleanupBlocked = "CleanupBlocked"

	// ReasonDeletionNotConfirmed means namespace deletion was requested but a
	// safety check failed, so the namespace was retained.
	ReasonDeletionNotConfirmed = "DeletionNotConfirmed"

	// ReasonTerminating means the profile is being deleted.
	ReasonTerminating = "Terminating"
)
